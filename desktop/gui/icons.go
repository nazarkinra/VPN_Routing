var iconCache = map[string]fyne.Resource{}

// icon — значок, окрашенный в цвет текста.
func icon(name string) fyne.Resource {
	if r, ok := iconCache[name]; ok {
		return r
	}
	svg := `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="#000000" d="` + iconPaths[name] + `"/></svg>`
	r := theme.NewThemedResource(fyne.NewStaticResource(name+".svg", []byte(svg)))
	iconCache[name] = r
	return r
}

// coloredIcon — значок своего цвета (не зависит от темы).
func coloredIcon(name, hex string) fyne.Resource {
	key := name + hex
	if r, ok := iconCache[key]; ok {
		return r
	}
	svg := `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="` + hex + `" d="` + iconPaths[name] + `"/></svg>`
	r := fyne.NewStaticResource(key+".svg", []byte(svg))
	iconCache[key] = r
	return r
}
